#!/usr/bin/env python3
"""Generate ds4_nfc_unicode.inc: the tables for NFC normalization in the
Qwen3.8 tokenizer path.

The reference is the Hugging Face `tokenizers` NFC normalizer, which every
released tokenizer.json with an NFC normalizer runs.  Its Unicode tables are
older than Python's, so properties come from `unicodedata` and are then kept
only where the tokenizers normalizer agrees: characters it does not know get
combining class 0 and no decomposition, exactly as it treats them.

    python3 gguf-tools/gen_nfc_unicode.py > ds4_nfc_unicode.inc
"""
import sys
import unicodedata as ud

from tokenizers import normalizers

HF_NFC = normalizers.NFC()
HF_NFD = normalizers.NFD()
SBASE, SCOUNT = 0xAC00, 11172


def chars():
    for cp in range(0x110000):
        if 0xD800 <= cp < 0xE000:
            continue
        yield cp


def hf_knows_ccc(cp, ccc):
    # A known mark is reordered against one of a different class.
    if ccc > 1:
        return HF_NFD.normalize_str(chr(cp) + "̴") == "̴" + chr(cp)
    return HF_NFD.normalize_str("́" + chr(cp)) == chr(cp) + "́"


def main():
    ccc = {}
    decomp = {}
    for cp in chars():
        c = ud.combining(chr(cp))
        if c and hf_knows_ccc(cp, c):
            ccc[cp] = c
        if SBASE <= cp < SBASE + SCOUNT:
            continue  # Hangul syllables are algorithmic
        d = ud.normalize("NFD", chr(cp))
        if d != chr(cp) and HF_NFD.normalize_str(chr(cp)) == d:
            decomp[cp] = [ord(x) for x in d]

    # Primary composites: canonical pairs that NFC recomposes to themselves.
    comp = {}
    for cp in chars():
        if cp not in decomp or SBASE <= cp < SBASE + SCOUNT:
            continue
        raw = ud.decomposition(chr(cp))
        if not raw or raw.startswith("<"):
            continue
        parts = [int(x, 16) for x in raw.split()]
        if len(parts) != 2:
            continue
        if HF_NFC.normalize_str(chr(parts[0]) + chr(parts[1])) == chr(cp):
            comp[(parts[0], parts[1])] = cp

    # The NFC quick check: characters NFC rewrites on their own (singletons,
    # exclusions), marks that may need reordering, and characters that may
    # combine with what precedes them.  Text with none of these is already
    # NFC; precomposed characters such as U+00E9 are left out, since they can
    # only change next to one of these.
    rewritten = {cp for cp in decomp if HF_NFC.normalize_str(chr(cp)) != chr(cp)}
    unstable = set(ccc) | rewritten | {b for (_, b) in comp}
    unstable |= set(range(0x1161, 0x1176)) | set(range(0x11A8, 0x11C3))

    def ranges(cps):
        out = []
        for cp in sorted(cps):
            if out and out[-1][1] == cp - 1:
                out[-1][1] = cp
            else:
                out.append([cp, cp])
        return out

    w = sys.stdout.write
    w("/* Generated by gguf-tools/gen_nfc_unicode.py from Python unicodedata %s,\n"
      " * restricted to what the Hugging Face tokenizers NFC normalizer knows.\n"
      " * Do not edit. */\n\n" % ud.unidata_version)

    w("typedef struct { uint32_t lo, hi; } ds4_nfc_range;\n")
    w("typedef struct { uint32_t lo, hi; uint8_t ccc; } ds4_nfc_ccc_range;\n")
    w("typedef struct { uint32_t cp; uint16_t off; uint8_t len; } ds4_nfc_decomp;\n")
    w("typedef struct { uint32_t first, second, composite; } ds4_nfc_pair;\n\n")

    cr = []
    for cp in sorted(ccc):
        if cr and cr[-1][1] == cp - 1 and cr[-1][2] == ccc[cp]:
            cr[-1][1] = cp
        else:
            cr.append([cp, cp, ccc[cp]])
    w("static const ds4_nfc_ccc_range ds4_nfc_ccc_ranges[] = {\n")
    for i in range(0, len(cr), 4):
        w("    " + " ".join("{0x%05x, 0x%05x, %d}," % tuple(r) for r in cr[i:i + 4]) + "\n")
    w("};\n\n")

    flat = []
    entries = []
    for cp in sorted(decomp):
        entries.append((cp, len(flat), len(decomp[cp])))
        flat.extend(decomp[cp])
    assert len(flat) < 65536 and max(e[2] for e in entries) < 256
    w("static const uint32_t ds4_nfc_decomp_cps[] = {\n")
    for i in range(0, len(flat), 8):
        w("    " + " ".join("0x%05x," % x for x in flat[i:i + 8]) + "\n")
    w("};\n\n")
    w("static const ds4_nfc_decomp ds4_nfc_decomps[] = {\n")
    for i in range(0, len(entries), 4):
        w("    " + " ".join("{0x%05x, %d, %d}," % e for e in entries[i:i + 4]) + "\n")
    w("};\n\n")

    w("static const ds4_nfc_pair ds4_nfc_pairs[] = {\n")
    pairs = sorted(comp.items())
    for i in range(0, len(pairs), 3):
        w("    " + " ".join("{0x%05x, 0x%05x, 0x%05x}," % (a, b, c)
                            for (a, b), c in pairs[i:i + 3]) + "\n")
    w("};\n\n")

    # One bit per 256-codepoint block holding any unstable character, so most
    # CJK, kana and Hangul text never reaches the range search.
    blocks = [0] * (0x110000 // 256 // 64)
    for cp in unstable:
        b = cp >> 8
        blocks[b >> 6] |= 1 << (b & 63)
    w("static const uint64_t ds4_nfc_unstable_blocks[] = {\n")
    for i in range(0, len(blocks), 4):
        w("    " + " ".join("0x%016xull," % x for x in blocks[i:i + 4]) + "\n")
    w("};\n\n")

    ur = ranges(unstable)
    w("static const ds4_nfc_range ds4_nfc_unstable_ranges[] = {\n")
    for i in range(0, len(ur), 4):
        w("    " + " ".join("{0x%05x, 0x%05x}," % tuple(r) for r in ur[i:i + 4]) + "\n")
    w("};\n")
    sys.stderr.write("ccc ranges %d, decompositions %d (%d cps), pairs %d, unstable ranges %d\n"
                     % (len(cr), len(entries), len(flat), len(pairs), len(ur)))


if __name__ == "__main__":
    main()
